def apply(R):
    """산업 JSON(R)의 회사에 about / deep 붙이기 — 없으면 그대로"""
    n = 0
    for c in R.get("companies", []):
        if c["t"] in ABOUT:
            c["about"] = ABOUT[c["t"]]; n += 1
        if c["t"] in DEEP:
            c["deep"] = DEEP[c["t"]]
        else:
            c.pop("deep", None)
    return n


